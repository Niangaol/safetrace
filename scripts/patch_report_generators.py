def main() -> int:
    total_ok = total_miss = 0
    for name in ("generate_report.py", "generate_word.py", "generate_ppt.py"):
        p = DIR / name
        if not p.exists():
            print(f"（缺 {name}）")
            continue
        text = p.read_text(encoding="utf-8")
        ok = miss = 0
        print(f"===== {name} =====")
        for old, new, desc in REPLACEMENTS:
            if old in text:
                text = text.replace(old, new)
                ok += 1
                print(f"  ✓ {desc}")
            else:
                miss += 1
                print(f"  - {desc}：原文未找到（可能该脚本没有这条）")
        p.write_text(text, encoding="utf-8")
        print(f"  小计：替换 {ok}，未命中 {miss}")
        total_ok += ok
        total_miss += miss
        print()
    print(f"合计：替换 {total_ok} 处，未命中 {total_miss} 处")
    print("未命中不等于失败：三个脚本内容不完全相同，某条只在其中一两个里出现是正常的。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
